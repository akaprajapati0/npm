        function rotate() {
            const cards = $('.card2');
            const firstCard = cards.first();

            firstCard.fadeOut(300, 'linear', function () {
                $(this).appendTo('.timeline-slider-container').hide().fadeIn(300, 'linear');
            });

            // Add zoom-in effect
            firstCard.css('transform', 'scale(1.05)');
            setTimeout(function () {
                firstCard.css('transform', '');
            }, 300);
        }

        function rotate2() {
            const cards = $('.card2');
            const lastCard = cards.last();

            lastCard.fadeOut(300, 'linear', function () {
                $(this).prependTo('.timeline-slider-container').hide().fadeIn(300, 'linear');

            });

            // Add zoom-in effect
            lastCard.css('transform', 'scale(1.05)');
            setTimeout(function () {
                lastCard.css('transform', '');
            }, 300);
        }

        $('.next').click(function () {
            rotate();
        });

        $('.prev').click(function () {
            rotate2();
        });
