            function getQueryString() {
                const path = window.location.search; // This gets the query string part
                return path ? path.substring(1) : ''; // Remove the "?" at the beginning
            }
            console.log("main url", getQueryString());


            // Retrieve the slug from the URL path
            let slug = getQueryString();
            slug = slug.replace(/-/g, ' ');
            let result = slug.split('/')[0];

            console.log("res", result);


            // console.log(partBeforeSlash);

            document.addEventListener('DOMContentLoaded', function () {
                const urlParams = new URLSearchParams(window.location.search);
                const categoryId = urlParams.get('category');
                const menuId = urlParams.get('id');
                console.log("Category ID:", categoryId, "Menu ID:", menuId, slug);

                fetch('https://ikrispharmanetwork.in/dashboard/getMenuData')
                    .then(response => response.json())
                    .then(data => {
                        const newsList = document.getElementById('newsList');
                        console.log("slug", slug);
                        // Find the selected menu by matching the id and category
                        const selectedMenu = data.menus.find(menu => menu.slug == slug);
                        console.log("selected", selectedMenu);
                        if (selectedMenu) {
                            // Set the menu details into the page
                            document.getElementById('categoryName').innerText = selectedMenu.category_name;
                            document.getElementById('menuName').innerText = selectedMenu.name;
                            document.getElementById('menuNameHeader').innerText = selectedMenu.name;
                            document.getElementById('menuImage').src =
                                `https://ikrispharmanetwork.in/dashboard/uploads/${selectedMenu.image}`;
                            document.getElementById('menuDescription').innerHTML = selectedMenu.description ||
                                'No description available';
                            document.getElementById('menuDate').innerText = formatDate(selectedMenu.createdAt);
                        } else {
                            newsList.innerHTML = 'Menu not found.';
                        }

                        // Function to format date
                        function formatDate(dateString) {
                            const date = new Date(dateString);
                            const day = date.getDate().toString().padStart(2, '0');
                            const month = (date.getMonth() + 1).toString().padStart(2, '0');
                            const year = date.getFullYear();
                            return `${day}-${month}-${year}`;
                        }

                        // If no specific menu id, show a list of items filtered by category
                        const filteredMenus = categoryId === 'all' ?
                            data.menus :
                            data.menus.filter(menu => menu.category_name == result);

                        // Limit to the first 3 items
                        const limitedMenus = filteredMenus.slice(0, 3);

                        limitedMenus.forEach(menu => {
                            const newsCard = document.createElement('div');
                            let slug = menu.slug; // Assuming you're getting the slug dynamically
                            slug = slug.replace(/ /g, '-');
                            const url = `https://ikrispharmanetwork.com/news_details.php?${slug}`;
                            newsCard.classList.add('col-lg-4');
                            newsCard.innerHTML = `
                            <a href="${url}">
                            <div class="announcement_box">
                                <div class="announcement_box2">
                                <span>${menu.category_name}</span>
                                <div class="announcement_box_date">${formatDate(menu.createdAt)}</div>
                                <h3>${menu.name.length > 50 ? menu.name.substring(0, 50) + '...' : menu.name}</h3>
                                </div>
                                <div class="announcement_box_img_outer">
                                <img src="https://ikrispharmanetwork.in/dashboard/uploads/${menu.image}" alt="">
                                </div>
                            </div>
                            </a>
                        `;
                            newsList.appendChild(newsCard);
                        });
                    })
                    .catch(error => console.error('Error fetching data:', error));
            });
        </script>



