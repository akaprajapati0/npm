                if (e.target === prescriptionModal) {
                    prescriptionModal.classList.remove("active");
                    document.body.style.overflow = "";
                }
            });

            document.addEventListener("keydown", function (e) {
                if (
                    e.key === "Escape" &&
                    prescriptionModal.classList.contains("active")
